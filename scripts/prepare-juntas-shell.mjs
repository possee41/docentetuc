import { createRequire } from 'node:module';
import { readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';

// Use Workerd already shipped with Wrangler. Render only the public empty
// document at build time, with no D1, credentials, account or external network.
export async function prepareJuntasShell() {
  const require = createRequire(realpathSync(resolve('node_modules/wrangler/package.json')));
  const { Miniflare } = require('miniflare');
  const root = resolve('dist/server');
  const modules = readdirSync(root, { recursive: true }).filter(file => /\.(?:js|mjs)$/.test(file) &&
    !['worker-entry.mjs', 'scheduled-task.mjs', 'juntas-shell.mjs', 'juntas-document.mjs'].includes(file))
    .map(file => ({ type: 'ESModule', path: join(root, file) }))
    .sort((a, b) => a.path === join(root, 'index.js') ? -1 : b.path === join(root, 'index.js') ? 1 : 0);
  const mf = new Miniflare({ modules, modulesRoot: root, compatibilityDate: '2026-05-15',
    compatibilityFlags: ['nodejs_compat'],
    outboundService: () => { throw Error('JUNTAS_BUILD_EXTERNAL_NETWORK_FORBIDDEN'); } });
  try {
    const documents = {};
    for (const section of ['padrones', 'comunicados']) {
      const response = await mf.dispatchFetch(`https://local.invalid/?section=${section}`, { headers: { Accept: 'text/html' } });
      const html = await response.text();
      if (response.status !== 200 || !html.startsWith('<!DOCTYPE html>') ||
          !html.includes('Cargando documentos oficiales') || response.headers.has('set-cookie'))
        throw Error('JUNTAS_PUBLIC_SHELL_INVALID');
      documents[section] = html;
    }
    writeFileSync(join(root, 'juntas-shell.mjs'), `// Generated by the same build; contains no records or sessions.\nexport default ${JSON.stringify(documents)};\n`);
  } finally { await mf.dispose(); }
}
